import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import dotenv from 'dotenv';
import pg from 'pg';
import { chromium, firefox } from 'playwright';
const env = dotenv.parse(readFileSync(new URL('../backend/.env', import.meta.url)));
assert.equal(env.OPSDESK_DEMO, 'true');
assert.equal(new URL(env.DATABASE_URL).hostname, '127.0.0.1');
const url = process.env.OPSDESK_BROWSER_URL || 'http://127.0.0.1:3000';
assert(['127.0.0.1', 'localhost'].includes(new URL(url).hostname));
const pool = new pg.Pool({ connectionString: env.DATABASE_URL });
const reference = ('BROWSER-APPROVAL-' + randomUUID().slice(0,8)).toUpperCase();
const engine = process.env.OPSDESK_BROWSER_ENGINE || 'chromium';
assert(['chromium', 'firefox'].includes(engine));
let browser;
try {
  const {rows: [seed]} = await pool.query(`SELECT * FROM "TravelBooking" WHERE reference='BK-1042'`);
  browser = await (engine === 'firefox' ? firefox : chromium).launch();
  const page = await browser.newPage();
  await page.goto(url);
  await page.getByLabel('Email address').fill('manager@opsdesk.demo');
  await page.getByLabel('Password', {exact: true}).fill('OpsDeskDemo!2026');
  await page.getByRole('button', {name: 'Sign in to workspace'}).click();
  await page.getByRole('button', {name: 'Booking reviews', exact: true}).click();
  const panel = page.getByRole('dialog', {name: 'Booking reviews', exact: true});
  await panel.getByLabel('Booking agency', {exact: true}).selectOption(seed.agencyId);
  await panel.getByLabel('Booking customer', {exact: true}).selectOption(seed.customerId);
  await panel.getByLabel('Booking supplier', {exact: true}).selectOption(seed.supplierId);
  await panel.getByLabel('Booking reference', {exact: true}).fill(reference);
  await panel.getByLabel('Destination', {exact: true}).fill('Synthetic approval destination');
  await panel.getByLabel('Service', {exact: true}).fill('Hotel');
  await panel.getByLabel('Check-in (UTC)', {exact: true}).fill('2027-02-01T10:00');
  await panel.getByLabel('Request reason', {exact: true}).fill('Browser synthetic booking approval rehearsal');
  await panel.getByRole('button', {name: 'Submit booking request', exact: true}).click();
  const creation = panel.locator('article').filter({hasText: reference}).filter({hasText: 'CREATE:'});
  await creation.getByText(/PENDING/).waitFor();
  await creation.getByRole('textbox').fill('Manager verified this synthetic booking request');
  await creation.getByRole('button', {name: 'Approve request', exact: true}).click();
  await creation.getByText(/APPROVED/).waitFor();
  const {rows: [booking]} = await pool.query(`SELECT id FROM "TravelBooking" WHERE reference=$1`, [reference]);
  assert(booking);
  await panel.getByLabel('Request type', {exact: true}).selectOption('CANCEL');
  await panel.getByLabel('Search Booking to cancel', {exact: true}).fill(reference);
  await panel.getByLabel('Booking to cancel', {exact: true}).selectOption(booking.id);
  await panel.getByLabel('Request reason', {exact: true}).fill('Browser cancellation after verified manager review');
  await panel.getByRole('button', {name: 'Submit booking request', exact: true}).click();
  const cancellation = panel.locator('article').filter({hasText: reference}).filter({hasText: 'CANCEL:'});
  await cancellation.getByText(/PENDING/).waitFor();
  await cancellation.getByRole('textbox').fill('Manager approves synthetic cancellation only');
  await cancellation.getByRole('button', {name: 'Approve request', exact: true}).click();
  await cancellation.getByText(/APPROVED/).waitFor();
  const {rows: [state]} = await pool.query(`SELECT "providerStatus" FROM "TravelBookingImport" WHERE "bookingId"=$1`, [booking.id]);
  assert.equal(state.providerStatus, 'CANCELLED');
  console.log(`Booking review ${engine} browser passed: request, create approval, cancellation and persistence.`);
} finally {
  await browser?.close();
  await pool.query(`DELETE FROM "MembershipAudit" WHERE "entityId" IN (SELECT id FROM "TravelBookingRequest" WHERE payload->>'reference'=$1)`, [reference]);
  await pool.query(`DELETE FROM "TravelBookingRequest" WHERE payload->>'reference'=$1`, [reference]);
  await pool.query(`DELETE FROM "TravelBooking" WHERE reference=$1`, [reference]);
  await pool.end();
}
